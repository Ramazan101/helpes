KYRGYZ_MARKERS: tuple[str, ...] = (
    "ө", "ү", "ң", "кандай", "иштебей", "жатат", "күйбөй", "жардам",
    "басып", "кагаз", "тармак", "жоок", "принтерди", "компьютерди",
)

FORBIDDEN_SECURITY_KEYWORDS: tuple[str, ...] = (
    "пароль", "пароли", "чужой аккаунт", "обойти", "взломать", "отключить антивирус",
    "права администратора без", "vpn обход", "чужую почту", "код подтверждения",
    "сырсөз", "паролду", "коопсуздукту айланып",
)


def detect_language(text: str) -> str:
    """Определяет язык обращения: 'ky' (кыргызский) или 'ru' (русский по умолчанию)."""
    lowered = (text or "").lower()
    for marker in KYRGYZ_MARKERS:
        if marker in lowered:
            return "ky"
    return "ru"


def is_security_sensitive_query(text: str) -> bool:
    """Проверяет, касается ли запрос паролей, учётных данных или обхода корпоративной защиты."""
    lowered = (text or "").lower()
    return any(keyword in lowered for keyword in FORBIDDEN_SECURITY_KEYWORDS)


def match_knowledge_items(query: str) -> list[KnowledgeItem]:
    """Находит подходящие инструкции из локальной базы знаний по тексту вопроса."""
    lowered = (query or "").lower()
    matched: list[KnowledgeItem] = []
    for item in KNOWLEDGE_BASE:
        if any(kw in lowered for kw in item.keywords):
            matched.append(item)
    return matched


def build_knowledge_context_for_prompt() -> str:
    """Формирует текстовую сводку базы знаний для системной инструкции языковой модели."""
    blocks: list[str] = []
    for item in KNOWLEDGE_BASE:
        steps = "\n".join(f"  {idx}. {step}" for idx, step in enumerate(item.steps_ru, start=1))
        blocks.append(
            f"Раздел: {item.title_ru}\n"
            f"Безопасные шаги проверки:\n{steps}\n"
            f"Когда создавать заявку: {item.when_to_ticket_ru}"
        )
    return "\n\n".join(blocks)

